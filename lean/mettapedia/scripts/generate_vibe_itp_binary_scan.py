#!/usr/bin/env python3
"""Generate small kernel-checked transitions for the actual binary source scanner.

The computed scanner states are untrusted candidates. Each transition and their
composition must be checked by Lean against the existing source reader.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from generate_vibe_itp_binary_source import LEAN_ROOT, NATIVE_ROOT, component_span

OUTPUT = LEAN_ROOT / "Mettapedia/Languages/VibeITP/Native/GeneratedBinaryScan.lean"


def quoted(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def source_segments(native: Path) -> list[str]:
    source = (native / "langdef/vibe-itp/vibe_itp_native_guest_v1.metta").read_text()
    start, end = component_span(source, source.index("(gslt-presentation-v1"))
    text = source[start:end]
    if any(character in text for character in [';', '"', '\\']):
        raise ValueError("this candidate-state exporter requires plain source atoms")
    return [text[position:min(position + 4, len(text) - 1)]
              for position in range(0, len(text) - 1, 4)] + [text[-1:]]

# Small blocks keep the elaboration budget local to a bounded set of rows.
REPLAY_BLOCK_ROWS = 32


def format_rows(command: str, rows: list[str]) -> list[str]:
    lines = []
    for start in range(0, len(rows), REPLAY_BLOCK_ROWS):
        lines.append(f"{command} {start} [")
        lines.append(",\n".join(rows[start:start + REPLAY_BLOCK_ROWS]))
        lines.extend(["]", ""])
    return lines


def suffix_blocks(command: str, count: int) -> list[str]:
    return [
        f"{command} {max(0, end - REPLAY_BLOCK_ROWS)} to {end} ending {count}"
        for end in range(count, 0, -REPLAY_BLOCK_ROWS)
    ]


def render(native: Path) -> str:
    chunks = source_segments(native)
    lines = [
        "import Mettapedia.GSLT.Parsing.SourceScanSegments",
        "import Mettapedia.GSLT.Parsing.SourceReaderReplay",
        "import Mettapedia.Languages.VibeITP.Native.GeneratedBinarySource",
        "import Batteries.Tactic.OpenPrivate",
        "",
        "/-! Checked replay candidates for the verbatim source scanner. Generated by",
        "`scripts/generate_vibe_itp_binary_scan.py`; every transition uses the original reader. -/",
        "",
        "set_option autoImplicit false",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 1000000",
        "set_option Elab.async false",
        "",
        "namespace Mettapedia.Languages.VibeITP.Native.GeneratedBinaryScan",
        "",
        "open Mettapedia.GSLT.Parsing.SourceScanSegments",
        "open private splitProgramForms parserDialectOf from Algorithms.MeTTa.Simple.Parser",
        "",
        "def reverse_000 : List Char := []",
        "def state_000 : ScanState := initialScanState",
        "",
        "theorem source_trimmed : GeneratedBinarySource.authoredBinaryText.trimAscii.toString =",
        "    GeneratedBinarySource.authoredBinaryText := by",
        "  apply trimAscii_of_boundary",
        "  · rw [GeneratedBinarySource.authoredBinaryText, String.toList_ofList]",
        "    have head : GeneratedBinarySource.authoredBinaryChars.head? = some '(' := by rfl",
        "    rw [head]",
        "    rfl",
        "  · rw [GeneratedBinarySource.authoredBinaryText, String.toList_ofList]",
        "    have tail : GeneratedBinarySource.authoredBinaryChars.getLast? = some ')' := by rfl",
        "    rw [tail]",
        "    rfl",
        "",
        "theorem source_nonempty : GeneratedBinarySource.authoredBinaryText.isEmpty = false := by",
        "  apply ofList_nonempty",
        "  intro equal",
        "  have heads := congrArg List.head? equal",
        "  change some '(' = none at heads",
        "  contradiction",
        "",
    ]
    depth = 0
    line = 1
    rows = []
    for chunk in chunks[:-1]:
        for character in chunk:
            line += character == '\n'
            depth += (character == '(') - (character == ')')
        if depth <= 0:
            raise ValueError("source span completed before its final character")
        rows.append(f"  {quoted(chunk)} {line} {depth}")
    lines.extend(format_rows("source_scan_replay", rows))

    previous = f"{len(chunks) - 1:03d}"
    final = f"{len(chunks):03d}"
    lines += [
        f"def segment_{previous} : String := {quoted(chunks[-1])}",
        f"def state_{final} : ScanState := makeScanState {line} 0 false false false false {line}",
        "  [] [(1, GeneratedBinarySource.authoredBinaryText)] none",
        f"theorem step_{previous} : segment_{previous}.toList.foldl step state_{previous} =",
        f"    state_{final} := by",
        f"  have characters : (')' :: reverse_{previous}).reverse =",
        "      GeneratedBinarySource.authoredBinaryChars := by rfl",
        f"  exact close_singleton_form {line} reverse_{previous}",
        "    GeneratedBinarySource.authoredBinaryText (congrArg String.ofList characters)",
        "    source_trimmed source_nonempty",
        "",
        f"def segments_{final} : List String := []",
        f"theorem tail_{final} : scanSegments state_{final} segments_{final} = state_{final} := rfl",
        "",
    ]
    lines.extend(suffix_blocks("source_scan_suffix", len(chunks)))
    lines.append("")
    lines += [
        "def segments : List String := segments_000",
        "",
        "theorem source_characters_exact : segments_000.flatMap String.toList =",
        "    GeneratedBinarySource.authoredBinaryChars := by rfl",
        "",
        "theorem source_segments_exact : concatenate segments_000 = GeneratedBinarySource.authoredBinaryText :=",
        "  concatenate_of_characters GeneratedBinarySource.authoredBinaryText segments_000",
        "    GeneratedBinarySource.authoredBinaryChars rfl source_characters_exact",
        "",
        "theorem scanned_exact : GeneratedBinarySource.authoredBinaryText.toList.foldl step initialScanState =",
        f"    state_{final} :=",
        "  scanned_source_of_segments_initial GeneratedBinarySource.authoredBinaryText segments_000",
        f"    state_000 state_{final} rfl source_segments_exact tail_000",
        "",
        "theorem split_forms_exact : splitProgramForms (parserDialectOf MeTTailCore.MeTTaSyntax.petta)",
        "    GeneratedBinarySource.authoredBinaryText = .ok [(1, GeneratedBinarySource.authoredBinaryText)] :=",
        f"  splitProgramForms_of_scanned GeneratedBinarySource.authoredBinaryText {line} scanned_exact",
        "",
        "end Mettapedia.Languages.VibeITP.Native.GeneratedBinaryScan",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native-root", type=Path, default=NATIVE_ROOT)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(args.native_root)
    if args.check:
        if not args.output.exists() or args.output.read_text() != content:
            parser.error("generated source scanner candidates are missing or stale")
    else:
        args.output.write_text(content)
    print("checked" if args.check else "generated", args.output.relative_to(LEAN_ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
