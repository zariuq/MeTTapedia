#!/usr/bin/env python3
"""Generate the hash-pinned Pure encodings of the frozen DTTBench-31 types."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from dataclasses import dataclass
from pathlib import Path


GROUPS = ("Eq", "Leq", "Logic", "Relation", "Set")
EXPECTED_COUNTS = {"Eq": 6, "Leq": 4, "Logic": 6, "Relation": 13, "Set": 2}
DEFINITION = re.compile(
    r"^def\s+([^\s:]+)\s*:\s*(.*?)\s*:=\s*by\b", re.MULTILINE | re.DOTALL
)


@dataclass(frozen=True)
class Statement:
    group: str
    name: str
    type_text: str
    type_sha256: str
    source_path: str
    source_sha256: str
    canonical_path: str
    canonical_sha256: str


def sha256_bytes(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def normalize_type(type_text: str) -> str:
    return re.sub(r"\s+", " ", type_text).strip()


def extract_types(path: Path) -> list[tuple[str, str]]:
    content = path.read_text(encoding="utf-8")
    definitions = [(match.group(1), match.group(2).strip()) for match in DEFINITION.finditer(content)]
    if not definitions:
        raise ValueError(f"no benchmark definitions found in {path.name}")
    return definitions


def lean_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def lean_identifier(group: str, name: str) -> str:
    safe = re.sub(r"[^0-9A-Za-z_]", "_", name)
    return f"goal_{group}_{safe}"


def collect(workspace: Path) -> list[Statement]:
    dtt_root = workspace / "repos" / "DTTBench" / "lean"
    canonical_root = workspace / "repos" / "Canonical-min" / "DTTBench-lean"
    statements: list[Statement] = []

    for group in GROUPS:
        source = dtt_root / f"{group}.lean"
        canonical = canonical_root / f"{group}.lean"
        source_bytes = source.read_bytes()
        canonical_bytes = canonical.read_bytes()
        source_types = extract_types(source)
        canonical_types = extract_types(canonical)

        if len(source_types) != EXPECTED_COUNTS[group]:
            raise ValueError(
                f"{group}: expected {EXPECTED_COUNTS[group]} definitions, found {len(source_types)}"
            )
        if [name for name, _ in source_types] != [name for name, _ in canonical_types]:
            raise ValueError(f"{group}: DTTBench and Canonical-min definition names/order differ")

        for (name, type_text), (_, canonical_type) in zip(source_types, canonical_types, strict=True):
            normalized = normalize_type(type_text)
            if normalized != normalize_type(canonical_type):
                raise ValueError(f"{group}.{name}: source type differs from Canonical-min phrasing")
            statements.append(
                Statement(
                    group=group,
                    name=name,
                    type_text=type_text,
                    type_sha256=sha256_bytes(normalized.encode("utf-8")),
                    source_path=f"repos/DTTBench/lean/{group}.lean",
                    source_sha256=sha256_bytes(source_bytes),
                    canonical_path=f"repos/Canonical-min/DTTBench-lean/{group}.lean",
                    canonical_sha256=sha256_bytes(canonical_bytes),
                )
            )

    if len(statements) != 31:
        raise ValueError(f"expected 31 statements, found {len(statements)}")
    if len({statement.name for statement in statements}) != len(statements):
        raise ValueError("DTTBench statement names are not unique")
    return statements


def indent_type(type_text: str) -> str:
    return "\n".join(f"    {line}" if line else "" for line in type_text.splitlines())


def render(statements: list[Statement], generator_sha256: str) -> str:
    lines = [
        "/-",
        "# Frozen DTTBench-31 Pure statements",
        "",
        "Generated by `scripts/generate_dttbench31_pure.py`.  The generator",
        "requires the DTTBench and Canonical-min statement types to agree before",
        "emitting this module.  Do not hand-edit this file.",
        "-/",
        "",
        "import Mettapedia.GSLT.LanguageDef.Pure.Encoding",
        "",
        "namespace Mettapedia.GSLT.LanguageDef.PureDTTBench31",
        "",
        "open Mettapedia.GSLT.LanguageDef.Pure",
        "",
        "/-- Provenance and elaborated Pure goal for one frozen benchmark statement. -/",
        "structure Statement where",
        "  group : String",
        "  name : String",
        "  sourcePath : String",
        "  sourceSha256 : String",
        "  canonicalPath : String",
        "  canonicalSha256 : String",
        "  normalizedTypeSha256 : String",
        "  goal : Expr",
        "  goalWellScoped : Expr.WellScoped 0 goal",
        "",
        f"def generatorSha256 : String := {lean_string(generator_sha256)}",
        "",
    ]

    for statement in statements:
        identifier = lean_identifier(statement.group, statement.name)
        lines.extend(
            [
                f"/-- `{statement.name}` reified from the frozen source type. -/",
                f"def {identifier} : Expr :=",
                "  pure_type% (",
                indent_type(statement.type_text),
                "  )",
                "",
                f"theorem {identifier}_wellScoped : Expr.WellScoped 0 {identifier} := by",
                "  apply (Expr.wellScoped_eq_true_iff 0 _).mp",
                "  decide",
                "",
            ]
        )

    lines.append("def statements : List Statement := [")
    for statement in statements:
        identifier = lean_identifier(statement.group, statement.name)
        lines.extend(
            [
                "  {",
                f"    group := {lean_string(statement.group)}",
                f"    name := {lean_string(statement.name)}",
                f"    sourcePath := {lean_string(statement.source_path)}",
                f"    sourceSha256 := {lean_string(statement.source_sha256)}",
                f"    canonicalPath := {lean_string(statement.canonical_path)}",
                f"    canonicalSha256 := {lean_string(statement.canonical_sha256)}",
                f"    normalizedTypeSha256 := {lean_string(statement.type_sha256)}",
                f"    goal := {identifier}",
                f"    goalWellScoped := {identifier}_wellScoped",
                "  },",
            ]
        )
    lines.extend(
        [
            "]",
            "",
            "/-- The frozen external test set contains exactly 31 statements. -/",
            "theorem statements_length : statements.length = 31 := by rfl",
            "",
            "/-- Every reified source statement survives the independent prefix parser. -/",
            "theorem statement_roundTrip (statement : Statement) :",
            "    Expr.decode statement.goal.encode = some statement.goal :=",
            "  Expr.decode_encode statement.goal",
            "",
            "/-- The round-trip theorem applies uniformly to every frozen statement. -/",
            "theorem allStatements_roundTrip :",
            "    ∀ statement ∈ statements,",
            "      Expr.decode statement.goal.encode = some statement.goal := by",
            "  intro statement _",
            "  exact statement_roundTrip statement",
            "",
            "/-- Every frozen statement is a closed goal of the Pure fragment. -/",
            "theorem allStatements_wellScoped :",
            "    ∀ statement ∈ statements, Expr.WellScoped 0 statement.goal := by",
            "  intro statement _",
            "  exact statement.goalWellScoped",
            "",
            "end Mettapedia.GSLT.LanguageDef.PureDTTBench31",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()

    script = Path(__file__).resolve()
    workspace = script.parents[4]
    output = script.parents[1] / "Mettapedia" / "GSLT" / "LanguageDef" / "Pure" / "DTTBench31.lean"
    statements = collect(workspace)
    rendered = render(statements, sha256_bytes(script.read_bytes()))

    if args.write:
        output.write_text(rendered, encoding="utf-8")
        print(f"generated {len(statements)} Pure statements")
        return 0

    if not output.exists() or output.read_text(encoding="utf-8") != rendered:
        print("DTTBench31.lean is missing or stale; run the generator with --write", file=sys.stderr)
        return 1
    print(f"verified {len(statements)} Pure statements and both source phrasings")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
