#!/usr/bin/env python3
"""Export compositional candidates for the original source lexer to check in Lean."""
from __future__ import annotations

import argparse
from pathlib import Path

from generate_vibe_itp_binary_source import LEAN_ROOT, NATIVE_ROOT
from generate_vibe_itp_binary_scan import format_rows, quoted, source_segments, suffix_blocks

OUTPUT = LEAN_ROOT / "Mettapedia/Languages/VibeITP/Native/GeneratedBinaryLex.lean"


def render(native: Path) -> str:
    chunks = source_segments(native)
    lines = [
        "import Mettapedia.Languages.VibeITP.Native.GeneratedBinaryScan",
        "import Mettapedia.GSLT.Parsing.SourceLexSegments",
        "import Mettapedia.GSLT.Parsing.SourceReaderReplay",
        "import Mettapedia.GSLT.Parsing.SExprTokenRoundTrip",
        "import Batteries.Tactic.OpenPrivate",
        "",
        "/-! Original-lexer replay candidates. Generated by",
        "`scripts/generate_vibe_itp_binary_lex.py`; every segment is kernel checked. -/",
        "",
        "set_option autoImplicit false",
        "set_option maxRecDepth 100000",
        "set_option maxHeartbeats 1000000",
        "set_option Elab.async false",
        "",
        "namespace Mettapedia.Languages.VibeITP.Native.GeneratedBinaryLex",
        "",
        "open Mettapedia.GSLT.Parsing.SourceScanSegments",
        "open Mettapedia.GSLT.Parsing.SourceLexSegments",
        "open Mettapedia.Languages.VibeITP.Native.GeneratedBinaryScan",
        "open private tokenizeAux tokenizeWith parserDialectOf from Algorithms.MeTTa.Simple.Parser",
        "",
        "def current_000 : List Char := []",
        "def reversedTokens_000 : List String := []",
        "",
    ]
    current = ""
    rows = []
    for chunk in chunks:
        emitted: list[str] = []
        for character in chunk:
            if character.isspace() or character in "()":
                if current:
                    emitted.append(current)
                    current = ""
                if character in "()":
                    emitted.append(character)
            else:
                current += character
        tokens = ", ".join(quoted(token) for token in reversed(emitted))
        rows.append(f"  {quoted(current)} [{tokens}]")
    lines.extend(format_rows("source_lex_replay", rows))
    final = f"{len(chunks):03d}"
    lines += [
        f"def input_{final} : List Char := []",
        f"theorem tail_{final} : lex input_{final} current_{final} reversedTokens_{final} =",
        f"    reversedTokens_{final}.reverse := lex_empty reversedTokens_{final}",
        "",
    ]
    lines.extend(suffix_blocks("source_lex_suffix", len(chunks)))
    lines.append("")
    lines += [
        "theorem input_characters_exact : input_000 = GeneratedBinarySource.authoredBinaryChars := by rfl",
        "",
        f"theorem tokens_exact : reversedTokens_{final}.reverse =",
        "    Mettapedia.GSLT.Parsing.SExprTokenRoundTrip.tokens GeneratedBinarySource.binarySyntax := by",
        "  rfl",
        "",
        "theorem lexed_exact : lex input_000 current_000 reversedTokens_000 =",
        "    Mettapedia.GSLT.Parsing.SExprTokenRoundTrip.tokens GeneratedBinarySource.binarySyntax :=",
        "  tail_000.trans tokens_exact",
        "",
        "theorem tokenized_exact : tokenizeWith (parserDialectOf MeTTailCore.MeTTaSyntax.petta)",
        "    GeneratedBinarySource.authoredBinaryText =",
        "      Mettapedia.GSLT.Parsing.SExprTokenRoundTrip.tokens GeneratedBinarySource.binarySyntax :=",
        "  tokenized_of_initial GeneratedBinarySource.authoredBinaryText",
        "    GeneratedBinarySource.authoredBinaryChars input_000 current_000 reversedTokens_000",
        "    (Mettapedia.GSLT.Parsing.SExprTokenRoundTrip.tokens GeneratedBinarySource.binarySyntax)",
        "    rfl input_characters_exact rfl rfl lexed_exact",
        "",
        "end Mettapedia.Languages.VibeITP.Native.GeneratedBinaryLex",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--native-root", type=Path, default=NATIVE_ROOT)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(args.native_root)
    if args.check:
        if not args.output.exists() or args.output.read_text() != content:
            parser.error("generated lexer candidates are missing or stale")
    else:
        args.output.write_text(content)
    print("checked" if args.check else "generated", args.output.relative_to(LEAN_ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
