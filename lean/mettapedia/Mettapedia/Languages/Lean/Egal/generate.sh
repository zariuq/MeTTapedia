#!/usr/bin/env bash
# Generate the Egal readings of Lean declarations, functions and computations.
#
#   generate.sh            writes generated/LeanFamilies.mg, generated/LeanFunctions.mg,
#                          generated/LeanComputations.mg and the control
#                          controls/reject_wrong_cetta_answer.mg
#   generate.sh --check    regenerates them beside the committed ones and compares
#
# Inputs:
#   artifacts/lean-declarations/families.metta  (scripts/ExportLeanDeclarations.lean)
#   artifacts/lean-declarations/terms.metta     (scripts/ExportLeanTerms.lean)
#   the answers of the code-equation slice on CeTTa (scripts/lean_code_equations_diff.py)
# The generators, generate.metta (families) and interpret.metta (functions and
# computations), are MeTTa programs run by CeTTa (PeTTa lane); they print one
# string per section, which is decoded here into Megalodon text.  Functions and
# computations that are not read are listed with their reasons.
#
#   CETTA   the CeTTa binary (default: cetta on PATH)
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
project=$(cd "$here/../../../.." && pwd)
cetta=${CETTA:-cetta}
families=(Nat Bool List Option Sum Prod Mettapedia.Languages.Lean.Declarations.Controls.Vec Eq Or And Iff
          Exists Nat.le Fin Add Zero False Decidable LT LE Max Ordering
          Mul One NPow Semigroup Monoid NSMul AddSemigroup AddMonoid AddCommMonoid)
decls=$project/artifacts/lean-declarations
work=$(mktemp -d "${TMPDIR:-/tmp}/lean-egal-generate.XXXXXX")
preserve_work=0
cleanup() {
  if [[ $preserve_work == 1 ]]; then
    echo "generation artifacts retained in $work" >&2
    return
  fi
  rm -f -- "$work"/*.metta "$work"/*.mg "$work"/*.txt "$work"/*.json "$work"/*.tsv
  rmdir -- "$work"
}
trap cleanup EXIT

# The functions' definitions are opaque in the computations, which use the
# proved equations only; checking needs no unfolding of large definitions.
opaque_open() {
  local names; names=$(sed -n 's/^Definition \([A-Za-z0-9_]*\) .*/\1/p' "$1" | tr '\n' ' ' | sed 's/ $//')
  [[ -n $names ]] && printf '%s\nOpaque %s.\n\n' "(** The runs use each function's proved equations, not its definition. **)" "$names"
  return 0
}
opaque_close() {
  local names; names=$(sed -n 's/^Definition \([A-Za-z0-9_]*\) .*/\1/p' "$1" | tr '\n' ' ' | sed 's/ $//')
  [[ -n $names ]] && printf '\nTransparent %s.\n' "$names"
  return 0
}

# Run a MeTTa driver; its printed strings become text, except those starting
# with "SKIP ", which are reasons and go to $work/skipped.txt.
run_metta() {
  "$cetta" --lang petta "$1" | python3 -c '
import sys, json
skipped = open(sys.argv[1], "a")
buffer = None
for line in sys.stdin:
    line = line.rstrip("\n")
    if buffer is None:
        if not line.startswith("\""):
            continue
        buffer = line
    else:
        buffer = buffer + "\n" + line
    try:
        text = json.loads(buffer, strict=False)
        buffer = None
    except json.JSONDecodeError:
        continue
    if text.startswith("SKIP "):
        skipped.write(text[5:] + "\n")
    else:
        print(text)
' "$work/skipped.txt"
}

# Families.
cat "$decls/families.metta" "$here/generate.metta" > "$work/families.metta"
for name in "${families[@]}"; do
  echo "!(let \$ls (egal-section $name) (map-atom \$ls \$l (println! \$l)))" >> "$work/families.metta"
done
{
  echo "(** Generated by generate.sh from the Lean declarations of"
  echo "    artifacts/lean-declarations/families.metta.  Do not edit. **)"
  echo
  run_metta "$work/families.metta"
} > "$work/LeanFamilies.mg"
closed=$(grep -c '^End .*_Section\.$' "$work/LeanFamilies.mg" || true)
if [[ "$closed" != "${#families[@]}" ]]; then
  echo "generate: $closed of ${#families[@]} sections generated"; exit 1
fi

# CeTTa's answers on the code-equation slice.
if ! python3 "$project/scripts/lean_code_equations_diff.py" --cetta "$cetta" \
    --report "$work/report.json" > "$work/slice.txt"; then
  cat "$work/slice.txt"; preserve_work=1; exit 1
fi
"$cetta" --lang petta --quiet "$here/answers.metta" "$work/report.json" \
  "$work/answers.metta" "$work/binary.txt" with-source "$project/artifacts/lean-code-equations/core/tests.tsv" > /dev/null
# The expected tests: every Lean test, answered by CeTTa or not.
ids=$(sed -n 's/^(LeanTest \([0-9]*\))$/\1/p' "$work/answers.metta")
tests=$(wc -w <<< "$ids")

# The typing lemmas proved in Egal by hand (proofs/functions/).
"$cetta" --lang petta "$here/splice.metta" facts "$here/proofs/functions" "$work/typing.metta" > /dev/null

reader() {
  cat "$decls/families.metta" "$decls/terms.metta" "$work/answers.metta" "$work/typing.metta" \
      "$here/support.metta" "$here/generate.metta" "$here/interpret.metta"
  printf '(EgalProofLibraryRoot "%s")\n' "$here"
}

# Functions.
{ reader
  echo '!(let $ls (functions-section) (map-atom $ls $l (println! $l)))'
  echo '!(let $fs (all-functions) (let $ls (refusal-lines $fs) (map-atom $ls $l (println! (format-args "SKIP function {}" ($l))))))'
} > "$work/functions.metta"
{
  echo "(** Generated by generate.sh: Lean functions read from their equation"
  echo "    theorems (artifacts/lean-declarations/terms.metta), each defined"
  echo "    through its family's recursor, with Lean's equation theorems proved"
  echo "    from the recursor's iota equations.  Do not edit. **)"
  echo
  run_metta "$work/functions.metta"
} > "$work/LeanFunctions.mg"

# Computations, and the control with a wrong answer.
{ reader
  echo '!(prepare-readability)'
  for i in $ids; do
    echo "!(case (computation-section $i) (((computation \$n \$t) (println! \$t)) ((stuck \$w) (println! (format-args \"SKIP test {}: {}\" ($i \$w))))))"
  done
} > "$work/computations.metta"
{
  echo "(** Generated by generate.sh: computations of the code-equation slice"
  echo "    (artifacts/lean-code-equations/core), each the reading of the Lean"
  echo "    term equal to the reading of CeTTa's answer, replayed by Lean's"
  echo "    equation theorems.  Answers from CeTTa's PeTTa evaluation.  Do not edit. **)"
  echo
  opaque_open "$work/LeanFunctions.mg"
  run_metta "$work/computations.metta"
  opaque_close "$work/LeanFunctions.mg"
} > "$work/LeanComputations.mg"
# Exactly one outcome per expected test; a defect stops the generation.
"$cetta" --lang petta "$here/accounted.metta" "$work/Outcomes.tsv" "$work/answers.metta" \
  "$work/LeanComputations.mg" "$work/skipped.txt" > /dev/null

{ reader
  echo '!(case (computation 6 (+ (answer-of 6) 1) Lean_test_06_wrong_answer) (((computation $n $t) (println! $t)) ((stuck $w) (println! (format-args "SKIP control: {}" ($w))))))'
} > "$work/control.metta"
{
  echo "(** Generated by generate.sh: test 6 with CeTTa's answer replaced by the"
  echo "    next integer.  Both checkers must refuse it. **)"
  run_metta "$work/control.metta"
} > "$work/reject_wrong_cetta_answer.mg"

# No line of generated text is longer than 200 characters.
# The hand-written proofs of typing lemmas, in place of their markers.
"$cetta" --lang petta "$here/splice.metta" splice "$here/proofs/functions" "$work/LeanFunctions.mg" > /dev/null

"$cetta" --lang petta "$here/wrap.metta" "$work"/*.mg > /dev/null
# Coverage of the slice's receipts: generated theorem candidates with the
# source statement digest checked at export, or a reason for their absence.
# The generator does not certify these proofs; check.sh runs both checkers.
python3 - "$project/artifacts/lean-code-equations/core/receipts.tsv" "$work/LeanFunctions.mg" \
  "$decls/terms.metta" "$work/skipped.txt" "$work/ReceiptCoverage.tsv" <<'PYEOF'
import re, sys
receipts, functions, terms, skipped, out = sys.argv[1:6]
rows = [line.rstrip("\n").split("\t") for line in open(receipts)][1:]
covered = {}
for line in open(functions):
    m = re.match(r"\(\*\* Receipt: (\S+) is the source of the MeTTa rule for (\S+), statement digest (\d+)", line)
    if m:
        covered[m.group(1)] = m.group(3)
projections = {}
for line in open(functions):
    m = re.match(r"\(\*\* Projection: (\S+), field", line)
    if m:
        projections[m.group(1)] = None
egal = {}
for line in open(terms):
    m = re.match(r"\(EgalName (\S+) (\S+)\)", line)
    if m:
        egal[m.group(1)] = m.group(2)
for name in projections:
    projections[name] = egal.get(name, name) + "_mk"
reasons = {}
for line in open(skipped):
    m = re.match(r"function (\S+): (.*)", line.rstrip("\n"))
    if m:
        reasons[m.group(1)] = m.group(2)
reached = set(re.findall(r"^\(Lean(?:Function|FunctionRefused) (\S+) ", open(terms).read(), re.M))
with open(out, "w") as f:
    f.write("receipt\tfunction\tkind\tstatement_digest\tegal\n")
    for function, theorem, kind, digest, _ in rows:
        if theorem in covered and covered[theorem] == digest:
            status = "generated " + egal[theorem]
        elif kind == "projection" and theorem in projections:
            status = "generated " + projections[theorem] + " (the projection's reduction)"
        elif kind == "projection":
            status = "not read: a structure projection"
        elif kind == "matcher-equation":
            status = "not read: a matcher of a function not read"
        elif function in reasons:
            status = "not read: " + reasons[function]
        elif function not in reached:
            status = "not read: not reached from a first-order test"
        else:
            status = "not read"
        f.write(f"{theorem}\t{function}\t{kind}\t{digest}\t{status}\n")
PYEOF

# Reuse the carried-target evidence checker with the slice's document parts.
# These conventional names live only in this generation directory.
cp "$work/LeanFamilies.mg" "$work/Families.mg"
cp "$work/LeanFunctions.mg" "$work/Functions.mg"
cp "$work/LeanComputations.mg" "$work/Computations.mg"
cp "$work/skipped.txt" "$work/Skipped.txt"
: > "$work/Theorems.mg"
"$cetta" --lang petta --quiet "$decls/terms.metta" "$decls/families.metta" "$here/evidence.metta" \
  "$work/Evidence.tsv" "$work/Qualification.tsv" "$work/EvidenceSummary.txt" "$decls" "$work" > /dev/null

outputs=(generated/LeanFamilies.mg generated/LeanFunctions.mg generated/LeanComputations.mg
         generated/ReceiptCoverage.tsv generated/Outcomes.tsv generated/Evidence.tsv generated/Qualification.tsv
         generated/EvidenceSummary.txt generated/Skipped.txt controls/reject_wrong_cetta_answer.mg)
if [[ "${1:-}" == "--check" ]]; then
  status=0
  for out in "${outputs[@]}"; do
    cmp -s "$work/$(basename "$out")" "$here/$out" || { echo "check: $out differs"; status=1; }
  done
  [[ $status == 0 ]] && echo "check: the generated files equal a fresh generation"
  [[ $status != 0 ]] && preserve_work=1
  exit $status
fi
for out in "${outputs[@]}"; do cp "$work/$(basename "$out")" "$here/$out"; done
echo "generated ${#families[@]} families: $(wc -l < "$here/generated/LeanFamilies.mg") lines"
echo "generated $(grep '^Definition' "$here/generated/LeanFunctions.mg" | grep -vc '_method[0-9]*_[0-9]* ') functions," \
     "$(grep -c '^Theorem' "$here/generated/LeanFunctions.mg") theorems," \
     "$(grep -c '^(\*\* Receipt:' "$here/generated/LeanFunctions.mg") of them receipts of the slice's MeTTa rules"
echo "generated $(grep -c '^Theorem Lean_test_[0-9]* :' "$here/generated/LeanComputations.mg") of $tests computations"
echo "receipts: $(grep -c $'\tgenerated ' "$here/generated/ReceiptCoverage.tsv") of $(($(wc -l < "$here/generated/ReceiptCoverage.tsv") - 1)) have generated theorem candidates; check.sh verifies them (generated/ReceiptCoverage.tsv)"
echo "not read:"; sed 's/^/  /' "$work/skipped.txt"
cat "$work/EvidenceSummary.txt"
