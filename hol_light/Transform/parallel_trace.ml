(* A trace identifies exactly the equations generated by the declared local
   exchanges and transports. Every Boolean observer respecting those
   generators must give the same result. Full HOL function quantification is
   essential; a finite suite of observers is not this definition. *)

let tc_generated_trace = new_definition
 `tc_generated_trace (generators:R->R->bool) left right <=>
    !observe:R->bool.
      (!one two. generators one two ==> (observe one <=> observe two)) ==>
      (observe left <=> observe right)`;;

let TC_TRACE_MEANING = prove
 (`!(generators:R->R->bool) left right.
     tc_generated_trace generators left right <=>
       !observe:R->bool.
         (!one two. generators one two ==> (observe one <=> observe two)) ==>
         (observe left <=> observe right)`,
  REWRITE_TAC[tc_generated_trace]);;

let TC_TRACE_GENERATOR = prove
 (`!(generators:R->R->bool) left right.
     generators left right ==> tc_generated_trace generators left right`,
  REWRITE_TAC[tc_generated_trace] THEN MESON_TAC[]);;

let TC_TRACE_REFL = prove
 (`!(generators:R->R->bool) state. tc_generated_trace generators state state`,
  REWRITE_TAC[tc_generated_trace]);;

let TC_TRACE_SYMM = prove
 (`!(generators:R->R->bool) left right.
     tc_generated_trace generators left right ==> tc_generated_trace generators right left`,
  REPEAT GEN_TAC THEN REWRITE_TAC[tc_generated_trace] THEN
  DISCH_THEN (LABEL_TAC "before") THEN X_GEN_TAC `observe:R->bool` THEN
  DISCH_THEN (LABEL_TAC "compatible") THEN
  USE_THEN "before" (fun before -> USE_THEN "compatible" (fun compatible ->
    ACCEPT_TAC (SYM (MATCH_MP (SPEC `observe:R->bool` before) compatible)))));;

let TC_TRACE_TRANS = prove
 (`!(generators:R->R->bool) first middle last.
     tc_generated_trace generators first middle /\ tc_generated_trace generators middle last ==>
     tc_generated_trace generators first last`,
  REPEAT GEN_TAC THEN REWRITE_TAC[tc_generated_trace] THEN
  DISCH_THEN (CONJUNCTS_THEN2 (LABEL_TAC "one") (LABEL_TAC "two")) THEN
  X_GEN_TAC `observe:R->bool` THEN DISCH_THEN (LABEL_TAC "compatible") THEN
  USE_THEN "one" (fun one -> USE_THEN "two" (fun two ->
    USE_THEN "compatible" (fun compatible ->
      ACCEPT_TAC (TRANS (MATCH_MP (SPEC `observe:R->bool` one) compatible)
        (MATCH_MP (SPEC `observe:R->bool` two) compatible))))));;

let TC_TRACE_LEAST = prove
 (`!(generators:R->R->bool) (relation:R->R->bool).
     (!a. relation a a) /\
     (!a b. relation a b ==> relation b a) /\
     (!a b c. relation a b /\ relation b c ==> relation a c) /\
     (!a b. generators a b ==> relation a b) ==>
     !left right. tc_generated_trace generators left right ==> relation left right`,
  REPEAT GEN_TAC THEN STRIP_TAC THEN REPEAT GEN_TAC THEN
  REWRITE_TAC[tc_generated_trace] THEN DISCH_THEN (LABEL_TAC "trace") THEN
  USE_THEN "trace" (MP_TAC o SPEC `\z:R. (relation:R->R->bool) (left:R) z`) THEN
  ANTS_TAC THENL [ASM_MESON_TAC[]; ASM_MESON_TAC[]]);;

let TC_TRACE_OBSERVER_DESCENT = prove
 (`!(generators:R->R->bool) observe.
     (!left right. tc_generated_trace generators left right ==> (observe left <=> observe right)) <=>
     (!left right. generators left right ==> (observe left <=> observe right))`,
  REPEAT GEN_TAC THEN EQ_TAC THENL
   [DISCH_THEN (LABEL_TAC "descent") THEN REPEAT GEN_TAC THEN DISCH_TAC THEN
    USE_THEN "descent" MATCH_MP_TAC THEN MATCH_MP_TAC TC_TRACE_GENERATOR THEN ASM_REWRITE_TAC[];
    REWRITE_TAC[tc_generated_trace] THEN DISCH_TAC THEN REPEAT GEN_TAC THEN
    DISCH_THEN (MP_TAC o SPEC `observe:R->bool`) THEN ASM_REWRITE_TAC[]]);;

let TC_TRACE_NO_GENERATORS = prove
 (`!left right:R. tc_generated_trace (\one two:R. F) left right <=> left = right`,
  REPEAT GEN_TAC THEN REWRITE_TAC[tc_generated_trace] THEN EQ_TAC THENL
   [DISCH_THEN (MP_TAC o SPEC `\z:R. z = (left:R)`) THEN SIMP_TAC[] THEN MESON_TAC[];
    DISCH_THEN SUBST1_TAC THEN REWRITE_TAC[]]);;

let TC_TRACE_EQUAL_ENDPOINTS_DISTINCT = prove
 (`((\event:bool. F) F = (\event:bool. F) T) /\
   ~(tc_generated_trace (\one two:bool. F) F T)`,
  REWRITE_TAC[TC_TRACE_NO_GENERATORS]);;
