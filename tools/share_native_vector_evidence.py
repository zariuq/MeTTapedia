def read_constructor(body, scoped_type, declarations):
    tokens = iter(match[0] for match in TOKEN.finditer(body) if not match[0].isspace())

    def read(expected, first):
        if first == "(":
            expression = read(expected, next(tokens))
            if next(tokens) != ")":
                raise ValueError("closing parenthesis expected")
            return expression
        if expected == "name" and first.startswith("`"):
            return first
        if expected in ("index", "nat") and first.isdecimal():
            return first
        if first in declarations:
            if declarations[first][0] != expected:
                raise ValueError(f"{first} has a different scope or sort")
            return first

        kind, _, scope = expected.partition(" ") if expected.startswith("Tower.Tm ") else (expected, "", "")
        namespace, signatures = CONSTRUCTORS[kind]
        if not first.startswith(namespace + "."):
            raise ValueError(f"unexpected constructor {first} for {expected}")
        fields = signatures[first.removeprefix(namespace + ".")]
        children = tuple(
            read(f"Tower.Tm {int(scope) + field}" if isinstance(field, int) else field, next(tokens))
            for field in fields
        )
        if first.endswith(".Tm.var") and int(children[0]) >= int(scope):
            raise ValueError("variable outside the certificate's scope")
        node = (expected, first, children)
        name = "syntax_" + sha256(repr(node).encode()).hexdigest()[:20]
        if declarations.setdefault(name, node) != node:
            raise ValueError(f"duplicate syntax name {name}")
        return name

    result = read(scoped_type, next(tokens))
    if next(tokens, None) is not None:
        raise ValueError("unexpected trailing syntax")
    return result


def canonical_table(declarations, roots, prefix):
    live = {}

    def retain(node):
        if node in live:
            return
        entry = declarations[node]
        for child in entry[-1]:
            if child.startswith(prefix):
                retain(child)
        live[node] = entry

    for node in sorted(roots):
        retain(node)
    needed = tuple(sorted(live))
    live.clear()
    for node in needed:
        retain(node)
    return live


@dataclass(frozen=True)
class ScopePlan:
    constructor: str
    children: tuple[str, ...]
    minimum: int


SCOPE_PLAN = re.compile(
    r"(?m)^private def (term_[0-9a-f]{20}) \(extra : Nat\)"
    r" : Tower\.Tm \(extra \+ (\d+)\) :=\n  ([^\n]+)\n\n"
)
SCOPE_INSTANCE = re.compile(
    r"(?m)^def (syntax_[0-9a-f]{20}) : Tower\.Tm (\d+)"
    r" := (term_[0-9a-f]{20}) (\d+)\n\n"
)
PLAN_ARGUMENT = re.compile(r"term_[0-9a-f]{20}|syntax_[0-9a-f]{20}|`[\w.]+")


def scope_fields(constructor):
    namespace, constructors = CONSTRUCTORS["Tower.Tm"]
    if not constructor.startswith(namespace + "."):
        raise ValueError(f"invalid term constructor {constructor}")
    return constructors[constructor.removeprefix(namespace + ".")]


def scope_plan(constructor, children, plans):
    fields = scope_fields(constructor)
    minimum = max((max(0, plans[child].minimum - field)
                   for child, field in zip(children, fields, strict=True)
                   if isinstance(field, int)), default=0)
    if constructor.endswith(".Tm.var"):
        minimum = int(children[0]) + 1
    key = "term_" + sha256(repr((constructor, children)).encode()).hexdigest()[:20]
    plan = ScopePlan(constructor, children, minimum)
    if plans.setdefault(key, plan) != plan:
        raise ValueError(f"duplicate scope plan {key}")
    return key


def scope_plan_body(plan, plans):
    if plan.constructor.endswith(".Tm.var"):
        index = int(plan.children[0])
        return (f".var ⟨{index}, Nat.lt_of_lt_of_le (Nat.lt_succ_self {index}) "
                f"(Nat.le_add_left {index + 1} extra)⟩")
    arguments = []
    for child, field in zip(plan.children, scope_fields(plan.constructor), strict=True):
        if isinstance(field, int):
            padding = plan.minimum + field - plans[child].minimum
            extra = f"(extra + {padding})" if padding else "extra"
            arguments.append(f"({child} {extra})")
        else:
            arguments.append(child)
    return " ".join((plan.constructor, *arguments))


def entries_in_row_block(block, row_pattern):
    rows = block[1].splitlines()
    for index, row in enumerate(rows):
        separated = index + 1 < len(rows)
        match = row_pattern.fullmatch(row.removesuffix(",") if separated else row)
        if not match or row.endswith(",") != separated:
            raise ValueError(f"invalid scoped syntax row {index + 1}")
        yield match.groups()


def entries_in_row_table(body, block_pattern, row_pattern):
    end = 0
    for block in block_pattern.finditer(body):
        if block.start() != end:
            raise ValueError(f"unexpected shared syntax at {end}")
        end = block.end()
        yield from entries_in_row_block(block, row_pattern)
    if end != len(body):
        raise ValueError(f"unexpected shared syntax at {end}")


def format_row_blocks(command, rows):
    return "".join(f"{command} [\n" + ",\n".join(rows[start:start + 128]) + "\n]\n\n"
                   for start in range(0, len(rows), 128))


def expand_syntax_rows(source, footer):
    """Read the row layout through the existing scoped declaration reader."""
    if not source.endswith(footer):
        raise ValueError("unexpected shared syntax module footer")
    body = source[len(SYNTAX_ROWS_HEADER):-len(footer)]
    declarations = []
    for name, parameter, annotation, value in entries_in_row_table(body, SYNTAX_ROWS, SYNTAX_ROW):
        if parameter:
            declarations.append(f"private def {name} (extra : Nat) : Tower.Tm (extra + {annotation}) :=\n"
                                f"  {value}\n\n")
        else:
            type_ = SYNTAX_SORTS.get(annotation, f"Tower.Tm {annotation}")
            assignment = " " if re.fullmatch(r"term_[0-9a-f]{20} \d+", value) else "\n"
            declarations.append(f"def {name} : {type_} :={assignment}{value}\n\n")
    return SYNTAX_MODULE_HEADER + "".join(declarations) + footer


def read_syntax_table(source):
    declarations, plans = {}, {}

    @cache
    def instantiate(key, arity):
        plan = plans[key]
        if arity < plan.minimum:
            raise ValueError(f"term plan {key} does not fit arity {arity}")
        children = tuple(instantiate(child, arity + field) if isinstance(field, int) else child
                         for child, field in zip(plan.children, scope_fields(plan.constructor), strict=True))
        node = (f"Tower.Tm {arity}", plan.constructor, children)
        name = "syntax_" + sha256(repr(node).encode()).hexdigest()[:20]
        if declarations.setdefault(name, node) != node:
            raise ValueError(f"duplicate syntax name {name}")
        return name

    footer = f"end {MODULE}\n"
    if source.startswith(SYNTAX_ROWS_HEADER):
        source = expand_syntax_rows(source, footer)
    if SCOPE_PLAN.search(source) or SCOPE_INSTANCE.search(source):
        if not source.startswith(SYNTAX_MODULE_HEADER) or not source.endswith(footer):
            raise ValueError("unexpected shared syntax module header")
        table = source[len(SYNTAX_MODULE_HEADER):-len(footer)]
        entries = sorted(
            (match.start(), match.end(), kind, match)
            for kind, pattern in (("plan", SCOPE_PLAN), ("instance", SCOPE_INSTANCE), ("direct", SYNTAX_ENTRY))
            for match in pattern.finditer(table)
        )
        end = 0
        for start, stop, _, _ in entries:
            if start != end:
                raise ValueError(f"unexpected shared syntax at {end}")
            end = stop
        if end != len(table):
            raise ValueError(f"unexpected shared syntax at {end}")
    else:
        entries = [(match.start(), match.end(), "direct", match) for match in SYNTAX_ENTRY.finditer(source)]
    for _, _, form, match in entries:
        if form == "plan":
            name, minimum, body = match.groups()
            if body.startswith(".var "):
                variable = re.match(r"\.var ⟨(\d+),", body)
                if variable is None:
                    raise ValueError(f"invalid variable in {name}")
                constructor, children = f"{PRESENTATION}.Tm.var", (variable[1],)
            else:
                constructor, _, arguments = body.partition(" ")
                children = tuple(PLAN_ARGUMENT.findall(arguments))
            for child, field in zip(children, scope_fields(constructor), strict=True):
                if field == "Tower.Head" and declarations.get(child, (None,))[0] != field:
                    raise ValueError(f"invalid head in scope plan {name}")
            key = scope_plan(constructor, children, plans)
            if key != name or plans[key].minimum != int(minimum) or scope_plan_body(plans[key], plans) != body:
                raise ValueError(f"invalid scope plan {name}")
        elif form == "instance":
            name, arity, key, extra = match.groups()
            plan = plans.get(key)
            if plan is None or plan.minimum + int(extra) != int(arity) or instantiate(key, int(arity)) != name:
                raise ValueError(f"invalid scope instance {name}")
        elif read_constructor(match[3], match[2], declarations) != match[1]:
            raise ValueError(f"changed constructor or scope for {match[1]}")
    return declarations


def format_syntax_table(declarations):
    plans, shape = {}, {}
    for name, (scoped_type, constructor, children) in declarations.items():
        if scoped_type.startswith("Tower.Tm "):
            arguments = tuple(shape[child] if isinstance(field, int) else child
                              for child, field in zip(children, scope_fields(constructor), strict=True))
            shape[name] = scope_plan(constructor, arguments, plans)
    counts = Counter(shape.values())
    emitted = set()
    table = []
    for name, (scoped_type, constructor, children) in declarations.items():
        key = shape.get(name)
        # Reuse the scope plan when it has several distinct instances.
        if counts[key] <= 3:
            annotation = SYNTAX_SORT_LABELS.get(scoped_type, scoped_type.removeprefix("Tower.Tm "))
            table.append(f"  {name} : {annotation} := {' '.join((constructor, *children))}")
            continue
        plan = plans[key]
        if key not in emitted:
            table.append(f"  {key} (extra) : {plan.minimum} := {scope_plan_body(plan, plans)}")
            emitted.add(key)
        arity = int(scoped_type.rsplit(" ", 1)[-1])
        if arity < plan.minimum:
            raise ValueError(f"term {name} does not fit arity {arity}")
        table.append(f"  {name} : {arity} := {key} {arity - plan.minimum}")
    return format_row_blocks("declare_tower_syntax", table)


def share(bundles, previous_module):
    declarations = read_syntax_table(previous_module)

    local_entries = {}
    needed = set()
    for name, source in bundles.items():
        entries = {
            match[1]: read_constructor(match[3], match[2], declarations)
            for match in VECTOR_SYNTAX.finditer(source)
        }
        needed.update(entries.values())
        needed.update(SHARED_NAME.findall(source))
        local_entries[name] = entries
    live = canonical_table(declarations, needed, "syntax_")

    output = {}
    for name, source in bundles.items():
        replacements = {local: f"{MODULE}.{node}" for local, node in local_entries[name].items()}
        retained = VECTOR_SYNTAX.sub(
            lambda match: "" if match[1] in replacements else match[0], source
        )
        retained = NAME.sub(
            lambda match: replacements.get(match[0], match[0]), retained
        )
        if replacements and f"import {MODULE}\n" not in retained:
            first_import, tail = retained.split("\n", 1)
            retained = f"{first_import}\nimport {MODULE}\n{tail}"
        output[name] = retained

    table = format_syntax_table(live)
    return output, SYNTAX_ROWS_HEADER + table + f"end {MODULE}\n"


