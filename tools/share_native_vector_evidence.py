def replay_template_entries(source):
    if not source:
        return
    footer = f"end {REPLAY_MODULE}\n"
    if not source.endswith(footer):
        raise ValueError("unexpected replay module footer")
    if source.startswith(REPLAY_MODULE_HEADER):
        body = source[len(REPLAY_MODULE_HEADER):-len(footer)]
        yield from entries_in_row_table(body, REPLAY_TEMPLATE_ROWS, REPLAY_TEMPLATE_ROW)
        return
    legacy_header = REPLAY_MODULE_HEADER.replace(REPLAY_ROWS_IMPORT, "")
    if not source.startswith(legacy_header):
        raise ValueError("unexpected replay module header")
    body = source[len(legacy_header):-len(footer)]
    end = 0
    for entry in REPLAY_ENTRY.finditer(body):
        if entry.start() != end:
            raise ValueError(f"unexpected replay declaration at {end}")
        end = entry.end()
        yield entry.groups()
    if end != len(body):
        raise ValueError(f"unexpected replay declaration at {end}")


def expand_private_replay(source):
    def expand(block):
        return "".join(f"private def {name} : {kind} {scope} :=\n{value}\n\n"
                       for name, kind, scope, value in entries_in_row_block(block, REPLAY_PRIVATE_ROW))

    expanded = REPLAY_PRIVATE_ROWS.sub(expand, source)
    if "\ndeclare_private_scoped_replay " in expanded:
        raise ValueError("unexpected private replay block layout")
    return expanded


def format_private_replay(source):
    def format_run(run):
        entries = REPLAY_LOCAL.findall(run[0])
        if len(entries) < 2:
            return run[0]
        rows = [f"  {name} : {kind} {scope} := {value}" for name, kind, scope, value in entries]
        return format_row_blocks("declare_private_scoped_replay", rows)

    formatted = REPLAY_LOCAL_RUN.sub(format_run, source)
    if formatted != source and REPLAY_ROWS_IMPORT not in source:
        line, remainder = formatted.split("\n", 1)
        formatted = f"{line}\n{REPLAY_ROWS_IMPORT}{remainder}"
    return formatted


def replay_node(body, kind, scope, resolved, declarations):
    constructor = body.split()[0]
    if constructor == ".root" or not REPLAY_ARGUMENTS.fullmatch(body):
        return None
    children = tuple(re.findall(r"\(([^()]*)\)", body))
    if any(child.startswith("e") and child not in resolved for child in children):
        return None
    children = tuple(
        resolved.get(child, child.removeprefix(f"{REPLAY_MODULE}.")) for child in children
    )
    for child in children:
        if child.startswith("replay_") and child not in declarations:
            raise ValueError(f"unresolved replay dependency {child}")
    key = (kind, scope, constructor, children)
    name = "replay_" + sha256(repr(key).encode()).hexdigest()[:20]
    if declarations.setdefault(name, key) != key:
        raise ValueError(f"duplicate replay name {name}")
    return name


def share_replay(bundles, previous_module):
    declarations = {}
    for name, kind, scope, body in replay_template_entries(previous_module):
        if replay_node(body, kind, scope, {}, declarations) != name:
            raise ValueError(f"changed structure or scope for {name}")

    local_entries = {}
    uses = Counter()
    retained = set()
    for name, source in bundles.items():
        retained.update(REPLAY_NAME.findall(source))
        entries = {}
        root_alias = ROOT_CODE_ALIAS.search(source)
        if name in REPLAY_BUNDLES and root_alias:
            expected = (
                f"private abbrev C (n : Nat) := StructuralConversionCode.Code Tower.Head {root_alias[1]}.Code n\n",
                "private abbrev T (n : Nat) := StructuralTypingReplay.Code Tower.Head C n\n",
                "private abbrev X (n : Nat) := StructuralTypingReplay.ContextCode Tower.Head C n\n",
            )
            if not all(alias in source for alias in expected):
                raise ValueError(f"unknown replay type in {name}")
            for match in REPLAY_LOCAL.finditer(source):
                shared = replay_node(match[4], match[2], match[3], entries, declarations)
                if shared:
                    entries[match[1]] = shared
                    uses[shared] += 1
        local_entries[name] = entries

    live = canonical_table(
        declarations, retained | {name for name, count in uses.items() if count > 1}, "replay_"
    )
    output = {}
    for name, source in bundles.items():
        replacements = {local: node for local, node in local_entries[name].items() if node in live}
        candidate = REPLAY_LOCAL.sub(lambda m: "" if m[1] in replacements else m[0], source)
        candidate = NAME.sub(lambda m: replacements.get(m[0], m[0]), candidate)
        if replacements and f"import {REPLAY_MODULE}\n" not in candidate:
            boundary = candidate.index("\n\n")
            candidate = candidate[:boundary] + f"\nimport {REPLAY_MODULE}" + candidate[boundary:]
        if replacements and f"open {REPLAY_MODULE}\n" not in candidate:
            first_abbrev = candidate.index("private abbrev S ")
            candidate = candidate[:first_abbrev] + f"open {REPLAY_MODULE}\n\n" + candidate[first_abbrev:]
        output[name] = candidate

    rows = [
        f"  {name} : {kind} {scope} := {constructor}{''.join(f' ({child})' for child in children)}"
        for name, (kind, scope, constructor, children) in live.items()
    ]
    table = format_row_blocks("declare_scoped_replay (RootCode)", rows)
    return output, REPLAY_MODULE_HEADER + table + f"end {REPLAY_MODULE}\n"


