#!/usr/bin/env python3
"""Share scoped Tower syntax and structural replay templates in the Vector evidence."""

import argparse
from collections import Counter
from hashlib import sha256
from pathlib import Path
import re


DECLARATIONS = "Mettapedia.TypeTheory.Calculi.CumulativePiSigmaId.Declarations"
MODULE = f"{DECLARATIONS}.NativeVectorEvidenceSyntax"
FOLD_MODULE = "Mettapedia.GSLT.LanguageDef.PositiveInductiveVectorTreeResultFoldEvidence"
BUNDLE_NAMES = (
    "FormationSensitiveNativeVectorAllOriginalInputUniversesEvidence",
    "FormationSensitiveNativeVectorAllUniverseMapEvidence",
    "NativeVectorAllResultMethodEvidence",
    "NativeVectorAllCommonRecursorEvidence",
    "FormationSensitiveNativeVectorAllResultUniverseEvidence",
    "FormationSensitiveNativeVectorAllResultsEvidence",
    "NativeNaturalVectorProgramEvidence",
    "NativeNaturalVectorAnnotatedEvidence",
)
REPLAY_BUNDLES = frozenset((
    "FormationSensitiveNativeVectorAllOriginalInputUniversesEvidence",
    "FormationSensitiveNativeVectorAllResultUniverseEvidence",
    "FormationSensitiveNativeVectorAllResultsEvidence",
    "NativeNaturalVectorProgramEvidence",
    "NativeVectorAllCommonRecursorEvidence",
    "NativeVectorAllResultMethodEvidence",
))
VECTOR_SYNTAX = re.compile(
    r"(?m)^private def (e\d+) : (Tower\.(?:Tm \d+|Head)) :=\n"
    r"([^\n]+(?:\n[ \t][^\n]*)*)\n\n"
)
SYNTAX_ENTRY = re.compile(
    r"(?m)^def (syntax_[0-9a-f]{20}) : (Tower\.(?:Tm \d+|Head)|LevelExpr Nat) :=\n"
    r"([^\n]+(?:\n[ \t][^\n]*)*)\n\n"
)
NAME = re.compile(r'(?<![\w.])e\d+\b|`[\w.]+|"(?:[^"\\]|\\.)*"|«[^»]*»')
SHARED_NAME = re.compile(rf"\b{re.escape(MODULE)}\.(syntax_[0-9a-f]{{20}})\b")
PRESENTATION = "Mettapedia.TypeTheory.Calculi.ParameterizedPiSigmaId.Presentation"
LEVELS = "Mettapedia.TypeTheory.UniverseLevel"
CONSTRUCTORS = {
    "Tower.Tm": (
        f"{PRESENTATION}.Tm",
        {
            "var": ("index",), "const": ("name",), "head": ("Tower.Head",),
            "pi": (0, 1), "sigma": (0, 1), "id": (0, 0, 0), "lam": (1,),
            "app": (0, 0), "pair": (0, 0), "fst": (0,), "snd": (0,), "refl": (0,),
        },
    ),
    "Tower.Head": (f"{PRESENTATION}.LevelTower.Head", {"sort": ("LevelExpr Nat",), "legacyGround": ()}),
    "LevelExpr Nat": (
        f"{LEVELS}.LevelExpr",
        {"param": ("nat",), "const": ("nat",), "succ": ("LevelExpr Nat",), "max": ("LevelExpr Nat", "LevelExpr Nat")},
    ),
}
TOKEN = re.compile(r"\s+|[()]|`[a-zA-Z_][\w.]*|[a-zA-Z_][\w.]*|[0-9]+|.", re.DOTALL)
SYNTAX_MODULE_HEADER = """\
import Mettapedia.TypeTheory.Calculi.ParameterizedPiSigmaId.Instances.UniverseProfiles

/-! Scoped syntax shared by the Vector certificates. The checking modules
replay each submission against its own signature, context, and judgment.
Generated by tools/share_native_vector_evidence.py. -/

namespace """ + MODULE + """

open Mettapedia.TypeTheory.Calculi.ParameterizedPiSigmaId.Presentation
open Mettapedia.TypeTheory.UniverseLevel

"""


def read_constructor(body, scoped_type, declarations):
    tokens = iter(match[0] for match in TOKEN.finditer(body) if not match[0].isspace())

    def read(expected, first):
        if first == "(":
            expression = read(expected, next(tokens))
            if next(tokens) != ")":
                raise ValueError("closing parenthesis expected")
            return expression
        if expected == "name" and first.startswith("`"):
            return first
        if expected in ("index", "nat") and first.isdecimal():
            return first
        if first in declarations:
            if declarations[first][0] != expected:
                raise ValueError(f"{first} has a different scope or sort")
            return first

        kind, _, scope = expected.partition(" ") if expected.startswith("Tower.Tm ") else (expected, "", "")
        namespace, signatures = CONSTRUCTORS[kind]
        if not first.startswith(namespace + "."):
            raise ValueError(f"unexpected constructor {first} for {expected}")
        fields = signatures[first.removeprefix(namespace + ".")]
        children = tuple(
            read(f"Tower.Tm {int(scope) + field}" if isinstance(field, int) else field, next(tokens))
            for field in fields
        )
        if first.endswith(".Tm.var") and int(children[0]) >= int(scope):
            raise ValueError("variable outside the certificate's scope")
        node = (expected, first, children)
        name = "syntax_" + sha256(repr(node).encode()).hexdigest()[:20]
        if declarations.setdefault(name, node) != node:
            raise ValueError(f"duplicate syntax name {name}")
        return name

    result = read(scoped_type, next(tokens))
    if next(tokens, None) is not None:
        raise ValueError("unexpected trailing syntax")
    return result


def canonical_table(declarations, roots, prefix):
    live = {}

    def retain(node):
        if node in live:
            return
        entry = declarations[node]
        for child in entry[-1]:
            if child.startswith(prefix):
                retain(child)
        live[node] = entry

    for node in sorted(roots):
        retain(node)
    needed = tuple(sorted(live))
    live.clear()
    for node in needed:
        retain(node)
    return live


def share(bundles, previous_module):
    declarations = {}
    for match in SYNTAX_ENTRY.finditer(previous_module):
        if read_constructor(match[3], match[2], declarations) != match[1]:
            raise ValueError(f"changed constructor or scope for {match[1]}")

    local_entries = {}
    needed = set()
    for name, source in bundles.items():
        entries = {
            match[1]: read_constructor(match[3], match[2], declarations)
            for match in VECTOR_SYNTAX.finditer(source)
        }
        needed.update(entries.values())
        needed.update(SHARED_NAME.findall(source))
        local_entries[name] = entries
    live = canonical_table(declarations, needed, "syntax_")

    output = {}
    for name, source in bundles.items():
        replacements = {local: f"{MODULE}.{node}" for local, node in local_entries[name].items()}
        retained = VECTOR_SYNTAX.sub(
            lambda match: "" if match[1] in replacements else match[0], source
        )
        retained = NAME.sub(
            lambda match: replacements.get(match[0], match[0]), retained
        )
        if replacements and f"import {MODULE}\n" not in retained:
            first_import, tail = retained.split("\n", 1)
            retained = f"{first_import}\nimport {MODULE}\n{tail}"
        output[name] = retained

    table = "".join(
        f"def {name} : {scoped_type} :=\n"
        f"{' '.join((constructor, *children))}\n\n"
        for name, (scoped_type, constructor, children) in live.items()
    )
    return output, SYNTAX_MODULE_HEADER + table + f"end {MODULE}\n"

REPLAY_MODULE = f"{DECLARATIONS}.NativeVectorReplayTemplates"
REPLAY_KEY = r"replay_[0-9a-f]{20}"
REPLAY_REF = rf"(?:{re.escape(REPLAY_MODULE)}\.)?({REPLAY_KEY})"
REPLAY_NAME = re.compile(rf"(?<![\w.]){REPLAY_REF}\b")
REPLAY_LOCAL = re.compile(r"(?m)^private def (e\d+) : ([SCTX]) (\d+) :=\n(\.[^\n]+)\n\n")
REPLAY_ENTRY = re.compile(
    rf"(?m)^def ({REPLAY_KEY}) : ([SCTX]) RootCode (\d+) :=\n(\.[^\n]+)\n\n"
)
REPLAY_ARGUMENTS = re.compile(
    rf"\.[A-Za-z]+(?: \((?:e\d+|{REPLAY_REF}|{re.escape(MODULE)}\.syntax_[0-9a-f]{{20}})\))*"
)
ROOT_CODE_ALIAS = re.compile(
    r"(?m)^private abbrev S \(n : Nat\) := StructuralConversionCode\.StepCode "
    r"Tower\.Head ([\w.]+)\.Code n$"
)
REPLAY_MODULE_HEADER = f"""import {MODULE}
import {PRESENTATION.rsplit('.', 1)[0]}.StructuralConversionCode
import {PRESENTATION.rsplit('.', 1)[0]}.StructuralTypingReplayFormation

/-! Shared structural replay templates. Each template is indexed by its binder
scope and polymorphic in the root-code family. The bundles supply their own
decoder payloads, signatures, and replay judgments.
Generated by tools/share_native_vector_evidence.py. -/

set_option autoImplicit false

namespace {REPLAY_MODULE}

open Mettapedia.TypeTheory.Calculi.ParameterizedPiSigmaId
open Presentation

private abbrev S (RootCode : Nat → Type) := StructuralConversionCode.StepCode Tower.Head RootCode
private abbrev C (RootCode : Nat → Type) := StructuralConversionCode.Code Tower.Head RootCode
private abbrev T (RootCode : Nat → Type) := StructuralTypingReplay.Code Tower.Head (C RootCode)
private abbrev X (RootCode : Nat → Type) := StructuralTypingReplay.ContextCode Tower.Head (C RootCode)

variable {{RootCode : Nat → Type}}

"""


def replay_node(body, kind, scope, resolved, declarations):
    constructor = body.split()[0]
    if constructor == ".root" or not REPLAY_ARGUMENTS.fullmatch(body):
        return None
    children = tuple(re.findall(r"\(([^()]*)\)", body))
    if any(child.startswith("e") and child not in resolved for child in children):
        return None
    children = tuple(
        resolved.get(child, child.removeprefix(f"{REPLAY_MODULE}.")) for child in children
    )
    for child in children:
        if child.startswith("replay_") and child not in declarations:
            raise ValueError(f"unresolved replay dependency {child}")
    key = (kind, scope, constructor, children)
    name = "replay_" + sha256(repr(key).encode()).hexdigest()[:20]
    if declarations.setdefault(name, key) != key:
        raise ValueError(f"duplicate replay name {name}")
    return name


def share_replay(bundles, previous_module):
    declarations = {}
    for match in REPLAY_ENTRY.finditer(previous_module):
        if replay_node(match[4], match[2], match[3], {}, declarations) != match[1]:
            raise ValueError(f"changed structure or scope for {match[1]}")

    local_entries = {}
    uses = Counter()
    retained = set()
    for name, source in bundles.items():
        retained.update(REPLAY_NAME.findall(source))
        entries = {}
        root_alias = ROOT_CODE_ALIAS.search(source)
        if name in REPLAY_BUNDLES and root_alias:
            expected = (
                f"private abbrev C (n : Nat) := StructuralConversionCode.Code Tower.Head {root_alias[1]}.Code n\n",
                "private abbrev T (n : Nat) := StructuralTypingReplay.Code Tower.Head C n\n",
                "private abbrev X (n : Nat) := StructuralTypingReplay.ContextCode Tower.Head C n\n",
            )
            if not all(alias in source for alias in expected):
                raise ValueError(f"unknown replay type in {name}")
            for match in REPLAY_LOCAL.finditer(source):
                shared = replay_node(match[4], match[2], match[3], entries, declarations)
                if shared:
                    entries[match[1]] = shared
                    uses[shared] += 1
        local_entries[name] = entries

    live = canonical_table(
        declarations, retained | {name for name, count in uses.items() if count > 1}, "replay_"
    )
    output = {}
    for name, source in bundles.items():
        replacements = {local: node for local, node in local_entries[name].items() if node in live}
        candidate = REPLAY_LOCAL.sub(lambda m: "" if m[1] in replacements else m[0], source)
        candidate = NAME.sub(lambda m: replacements.get(m[0], m[0]), candidate)
        if replacements and f"import {REPLAY_MODULE}\n" not in candidate:
            boundary = candidate.index("\n\n")
            candidate = candidate[:boundary] + f"\nimport {REPLAY_MODULE}" + candidate[boundary:]
        if replacements and f"open {REPLAY_MODULE}\n" not in candidate:
            first_abbrev = candidate.index("private abbrev S ")
            candidate = candidate[:first_abbrev] + f"open {REPLAY_MODULE}\n\n" + candidate[first_abbrev:]
        output[name] = candidate

    table = "".join(
        f"def {name} : {kind} RootCode {scope} :=\n"
        f"{constructor}{''.join(f' ({child})' for child in children)}\n\n"
        for name, (kind, scope, constructor, children) in live.items()
    )
    return output, REPLAY_MODULE_HEADER + table + f"end {REPLAY_MODULE}\n"


def share_evidence(bundles, previous_syntax, previous_replay):
    # A proof template can be the sole user of one of the syntax nodes.
    sources = dict(bundles, replay=previous_replay)
    syntax_output, syntax_table = share(sources, previous_syntax)
    replay_input = syntax_output.pop("replay")
    replay_output, replay_table = share_replay(syntax_output, replay_input)
    final_output, syntax_table = share(dict(replay_output, replay=replay_table), syntax_table)
    replay_table = final_output.pop("replay")
    return final_output, syntax_table, replay_table


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="apply the shared layout")
    parser.add_argument(
        "--package-dir",
        type=Path,
        default=Path(__file__).resolve().parents[1].joinpath("lean", "mettapedia"),
        help="Lean package containing the generated bundles",
    )
    args = parser.parse_args()
    declarations = args.package_dir.joinpath(*DECLARATIONS.split("."))
    paths = {name: declarations / f"{name}.lean" for name in BUNDLE_NAMES}
    fold_path = args.package_dir.joinpath(*FOLD_MODULE.split(".")).with_suffix(".lean")
    paths[fold_path.stem] = fold_path
    bundles = {name: path.read_text() for name, path in paths.items()}
    table_path = declarations / "NativeVectorEvidenceSyntax.lean"
    replay_path = declarations / "NativeVectorReplayTemplates.lean"
    previous_syntax = table_path.read_text() if table_path.exists() else ""
    previous_replay = replay_path.read_text() if replay_path.exists() else ""
    output, table, replay_table = share_evidence(bundles, previous_syntax, previous_replay)
    before = sum(source.count("\n") for source in bundles.values()) + (
        previous_syntax.count("\n") + previous_replay.count("\n")
    )
    after = sum(source.count("\n") for source in output.values()) + (
        table.count("\n") + replay_table.count("\n")
    )
    print(f"Vector evidence source lines: {before:,} → {after:,}")
    if bundles == output and previous_syntax == table and previous_replay == replay_table:
        return 0
    if not args.write:
        return 1
    if previous_syntax != table:
        table_path.write_text(table)
    if previous_replay != replay_table:
        replay_path.write_text(replay_table)
    for name, path in paths.items():
        if output[name] != bundles[name]:
            path.write_text(output[name])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
